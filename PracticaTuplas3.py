# ------------------------------------------------------------
# Extrae los elementos de la siguiente tupla en cuatro
# variables: a, b, c y d.
# ------------------------------------------------------------

mi_tupla = (1, 2, 3, 4)


# ------------------------------------------------------------
# Desempaquetar los elementos de la tupla
# Cada elemento de la tupla se asigna a una variable.
# La cantidad de variables debe coincidir con la cantidad
# de elementos que contiene la tupla.
# ------------------------------------------------------------

a, b, c, d = mi_tupla


# ------------------------------------------------------------
# Mostrar los valores de las variables
# Se imprime el valor que fue asignado a cada variable.
# ------------------------------------------------------------

print(a)  # Imprime: 1
print(b)  # Imprime: 2
print(c)  # Imprime: 3
print(d)  # Imprime: 4

### Otra forma de imprimir los valores de las variables en una sola línea
print(a, b, c, d)  # Imprime: 1 2 3 4