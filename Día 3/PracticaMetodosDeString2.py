# ------------------------------------------------------------
# Este programa utiliza el método join() para unir todos los
# elementos de la lista en un solo string, utilizando un
# espacio como separador entre cada elemento.
# ------------------------------------------------------------

lista_palabras = ["La", "legibilidad", "cuenta."]

# Unimos los elementos de la lista utilizando un espacio.
frase_unida = " ".join(lista_palabras)

print(frase_unida)