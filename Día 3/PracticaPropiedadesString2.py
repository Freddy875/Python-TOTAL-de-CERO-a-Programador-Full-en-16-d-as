# ------------------------------------------------------------
# Este programa utiliza el operador not in para comprobar que
# la palabra "agua" no se encuentre dentro del haiku. El
# resultado de la comprobación es un valor booleano: True si
# la palabra no se encuentra y False si sí se encuentra.
# ------------------------------------------------------------

haiku = """Tierra mojada,
mis recuerdos de viaje
entre las lluvias"""

resultado = "agua" not in haiku

print(resultado)