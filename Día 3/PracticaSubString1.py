# ------------------------------------------------------------
# Este programa utiliza slicing para extraer la primera
# palabra de una frase. Como "Controlar" tiene 9 caracteres,
# se utiliza [:9] para obtener los caracteres desde el inicio
# de la frase hasta antes de la posición 9.
# ------------------------------------------------------------

frase = "Controlar la complejidad es la esencia de la programación"

primera_palabra = frase[:9]

print(primera_palabra)