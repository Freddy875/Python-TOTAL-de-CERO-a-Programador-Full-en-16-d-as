# ------------------------------------------------------------
# Práctica Booleanos 5
# Verifica si la raíz cuadrada de 25 es igual a 5 y muestra
# el resultado booleano en pantalla utilizando print().
# ------------------------------------------------------------


# ------------------------------------------------------------
# Importar el módulo math
# El módulo math proporciona funciones matemáticas, como
# sqrt(), que permite calcular raíces cuadradas.
# ------------------------------------------------------------

import math


# ------------------------------------------------------------
# Calcular y comparar la raíz cuadrada
# math.sqrt(25) calcula la raíz cuadrada de 25.
# Después, el operador == comprueba si el resultado es igual a 5.
# ------------------------------------------------------------

resultado = math.sqrt(25) == 5


# ------------------------------------------------------------
# Mostrar el resultado
# Se imprime el valor booleano almacenado en la variable
# resultado.
# ------------------------------------------------------------

print(resultado)  # Imprime: True