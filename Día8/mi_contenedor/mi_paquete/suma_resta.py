def suma(numero1, numero2):
    """
    Función que suma dos números.

    Args:
        numero1 (float): Primer número a sumar.
        numero2 (float): Segundo número a sumar.

    Returns:
        float: La suma de los dos números.
    """
    return numero1 + numero2

def resta(numero1, numero2):
    """
    Función que resta dos números.

    Args:
        numero1 (float): Primer número.
        numero2 (float): Segundo número a restar del primero.

    Returns:
        float: La resta de los dos números.
    """
    return numero1 - numero2