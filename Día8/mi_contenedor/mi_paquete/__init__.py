# Objetivo: Convertir la carpeta mi_paquete en un
# paquete de Python.
# Un paquete es una carpeta que agrupa varios módulos
# relacionados; el archivo __init__.py le indica a
# Python que la carpeta es un paquete y que se pueden
# importar los módulos que contiene, por ejemplo:
# from mi_paquete import suma_resta
# Este archivo puede quedar vacío, como en este caso;
# el código que se escriba aquí se ejecuta en cuanto
# se importa el paquete.
# Estructura del paquete:
# mi_paquete/
#     __init__.py    -> marca la carpeta como paquete
#     suma_resta.py  -> funciones suma() y resta()
