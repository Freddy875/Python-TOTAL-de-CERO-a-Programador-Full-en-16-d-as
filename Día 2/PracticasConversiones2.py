# ------------------------------------------------------------
# Este programa declara una variable de tipo entero (int)
# y la convierte explícitamente a un número decimal (float)
# utilizando la función float(). Finalmente, muestra en
# pantalla el tipo de dato resultante después de la
# conversión.
# ------------------------------------------------------------

num2 = 10  # Variable original de tipo entero.

num2 = float(num2)  # Convertimos num2 a un número decimal (float).

print(type(num2))  # Mostramos el tipo de dato después de la conversión.