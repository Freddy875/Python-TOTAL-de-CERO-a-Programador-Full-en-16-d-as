# ------------------------------------------------------------
# Programa: Operadores aritméticos en Python
#
# Este programa muestra el funcionamiento de los principales
# operadores aritméticos utilizando tres variables
# numéricas. Cada operación se presenta con una explicación
# y su resultado en pantalla.
# ------------------------------------------------------------

num1 = 6
num2 = 2
num3 = 7


# ------------------------------------------------------------
# Suma (+)
# Suma el valor de dos números y muestra el resultado.
# ------------------------------------------------------------

print(f"{num1} más {num2} es igual a {num1 + num2}")


# ------------------------------------------------------------
# Resta (-)
# Resta el segundo número al primero y muestra el resultado.
# ------------------------------------------------------------

print(f"{num1} menos {num2} es igual a {num1 - num2}")


# ------------------------------------------------------------
# Multiplicación (*)
# Multiplica dos números y muestra el resultado.
# ------------------------------------------------------------

print(f"{num1} por {num2} es igual a {num1 * num2}")


# ------------------------------------------------------------
# División (/)
# Divide el primer número entre el segundo y devuelve un
# resultado de tipo decimal (float).
# ------------------------------------------------------------

print(f"{num1} entre {num2} es igual a {num1 / num2}")


# ------------------------------------------------------------
# División entera (//)
# Devuelve únicamente la parte entera del resultado de la
# división, descartando los decimales.
# ------------------------------------------------------------

print(f"{num3} dividido al piso entre {num2} es igual a {num3 // num2}")


# ------------------------------------------------------------
# Módulo (%)
# Devuelve el residuo o resto de una división.
# ------------------------------------------------------------

print(f"{num3} módulo {num2} es igual a {num3 % num2}")


# ------------------------------------------------------------
# Potenciación (**)
# Eleva un número a la potencia indicada.
# ------------------------------------------------------------

print(f"{num1} elevado a la {num2} es igual a {num1 ** num2}")


# ------------------------------------------------------------
# Potencia al cubo
# Eleva un número a la tercera potencia.
# ------------------------------------------------------------

print(f"{num1} elevado al cubo es igual a {num1 ** 3}")


# ------------------------------------------------------------
# Raíz cuadrada
# Calcula la raíz cuadrada de un número elevándolo a la
# potencia 0.5.
# ------------------------------------------------------------

print(f"La raíz cuadrada de {num1} es igual a {num1 ** 0.5}")