# ------------------------------------------------------------
# Este programa utiliza el método upper() para convertir
# todos los caracteres de la frase a mayúsculas. El resultado
# se guarda en una nueva variable y se muestra en pantalla.
# ------------------------------------------------------------

frase = "Especialmente en las comunicaciones electrónicas, la escritura enteramente en mayúsculas equivale a gritar."

# Convertimos la frase a mayúsculas.
frase_mayusculas = frase.upper()

print(frase_mayusculas)