# Importamos la librería random para poder utilizar
# sus funciones relacionadas con números aleatorios.
import random

# ------------------------------------------------------------
# Genera un número decimal aleatorio entre 0 y 1.
# random() devuelve un valor mayor o igual a 0
# y menor que 1.
# ------------------------------------------------------------

aleatorio = random.random()

# ------------------------------------------------------------
# Imprime el número decimal aleatorio generado.
# ------------------------------------------------------------

print(aleatorio)