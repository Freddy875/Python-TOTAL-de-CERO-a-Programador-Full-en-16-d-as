# Utiliza la función randint() de la librería random
# para obtener un número entero aleatorio del 1 al 10.
# El resultado se almacena en la variable aleatorio.
# ------------------------------------------------------------

# Importamos la librería random para poder utilizar
# sus funciones relacionadas con números aleatorios.
import random

# ------------------------------------------------------------
# Genera un número entero aleatorio entre 1 y 10.
# randint() incluye tanto el valor inicial como el final.
# ------------------------------------------------------------

aleatorio = random.randint(1, 10)

# ------------------------------------------------------------
# Imprime el número entero aleatorio generado.
# ------------------------------------------------------------

print(aleatorio)