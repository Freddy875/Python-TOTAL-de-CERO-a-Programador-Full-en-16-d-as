# ------------------------------------------------------------
# Práctica Operadores de Comparación 1
#
# Crea dos variables (num1 y num2) con los valores 36 y 17
# respectivamente. Verifica si num1 es mayor o igual que num2
# y almacena el resultado de dicha comparación en una variable
# llamada mi_bool.
# ------------------------------------------------------------

# ------------------------------------------------------------
# Definir las variables
# Se crean las variables num1 y num2 y se les asignan
# los valores 36 y 17 respectivamente.
# ------------------------------------------------------------

num1 = 36
num2 = 17


# ------------------------------------------------------------
# Verificar si num1 es mayor o igual que num2
# El operador >= comprueba si num1 es mayor o igual que num2.
# El resultado de la comparación se guarda en mi_bool.
# ------------------------------------------------------------

mi_bool = num1 >= num2


# ------------------------------------------------------------
# Imprimir el resultado
# Se muestra el valor booleano obtenido de la comparación.
# ------------------------------------------------------------

print(mi_bool)
# Imprime: True