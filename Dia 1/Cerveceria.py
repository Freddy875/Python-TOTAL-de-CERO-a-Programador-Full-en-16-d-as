# Programa: Generador de nombres para una marca de cerveza
#
# Este programa solicita al usuario una ciudad o un país que
# le gustaría visitar y su color favorito. Luego combina ambas
# respuestas para crear un nombre creativo para una marca de
# cerveza y lo muestra en pantalla.
