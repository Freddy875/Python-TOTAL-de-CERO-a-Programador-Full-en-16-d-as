# Programa: Generador de nombres para una marca de cerveza
#
# Este programa solicita al usuario dos datos: su animal
# favorito y su color favorito. Con esta información crea
# un nombre original para una marca de cerveza combinando
# ambas respuestas y lo muestra en pantalla.
