# ------------------------------------------------------------
# Realizar una comparación
# El operador > comprueba si el número 10 es mayor que 5.
# El resultado de la comparación es un valor booleano.
# ------------------------------------------------------------

prueba = 10 > 5  # El resultado es: True


# ------------------------------------------------------------
# Mostrar el resultado
# Se imprime el valor booleano almacenado en la variable
# prueba.
# ------------------------------------------------------------

print(prueba)  # Imprime: True